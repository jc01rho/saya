import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { generateContract } from "./contract-generate";

export const extensionDirectory = new URL(
  "../src/contract/piratetalk/",
  import.meta.url,
);
export const extensionSource = new URL(
  "../contracts/piratetalk-extension.openapi.json",
  import.meta.url,
);
export const corpusSource = new URL(
  "../contracts/piratetalk-extension.fixtures.json",
  import.meta.url,
);
export const extensionHash =
  "6621371a9f36af6fdf360a12a790b615dd61e290dc020caeea5ae8f687a6ade9";
export const corpusHash =
  "8c74035d96ea0da52df40768696bed9e637ffe8fc23cbfea2689dcb2621eb951";

export async function pinnedBytes(path: URL, hash: string): Promise<string> {
  const bytes = await readFile(path);
  if (createHash("sha256").update(bytes).digest("hex") !== hash)
    throw new Error(`Extension byte identity failed: ${path.pathname}`);
  return bytes.toString("utf8");
}

export async function generateExtension(): Promise<Map<string, string>> {
  const files = await generateContract({
    source: "contracts/piratetalk-extension.openapi.json",
    hash: extensionHash,
    directory: extensionDirectory,
    sse: false,
    widen(_document, decoded) {
      // OpenAPI binary is a transport annotation, not a JSON Schema format.
      // JSON fixtures exercise the field shape; multipart byte checks belong to core.
      const stripBinary = (value: unknown): void => {
        if (Array.isArray(value)) {
          for (const child of value) stripBinary(child);
        } else if (value !== null && typeof value === "object") {
          if ("format" in value && value.format === "binary")
            Reflect.deleteProperty(value, "format");
          for (const child of Object.values(value)) stripBinary(child);
        }
      };
      stripBinary(decoded);
    },
  });
  for (const [name, content] of files)
    files.set(
      name,
      content
        .replaceAll("bun run contract:generate", "bun run extension:generate")
        .replace(/^\/\/ .*node_modules\/ajv\//gm, "// node_modules/ajv/"),
    );
  const boundary = await readFile(
    new URL("./extension-boundary.template", import.meta.url),
    "utf8",
  );
  files.set(
    "boundary.ts",
    `// Generated by bun run extension:generate. Do not edit.\n${boundary}`,
  );
  return files;
}

if (import.meta.main) {
  const files = await generateExtension();
  await mkdir(extensionDirectory, { recursive: true });
  for (const [name, content] of files)
    await writeFile(new URL(name, extensionDirectory), content);
  console.log(
    `Generated ${files.size} extension artifacts; canonical artifacts untouched`,
  );
}
